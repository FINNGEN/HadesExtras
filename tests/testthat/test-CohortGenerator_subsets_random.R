# createRandomSubset

test_that("Random subset naming and instantiation", {
  randomSubset <- createRandomSubset(
    name = NULL,
    numberOfSubjects = 25,
    randomSeed = 12345
  )

  expect_s3_class(randomSubset, "RandomSubsetOperator")
  expect_equal(randomSubset$numberOfSubjects, 25L)
  expect_equal(randomSubset$randomSeed, 12345L)
  expect_equal(
    randomSubset$getAutoGeneratedName(),
    "Random subset of 25 subjects with seed 12345"
  )

  randomSubset$name <- "sampled cases"
  expect_equal(randomSubset$name, "sampled cases")
})


test_that("Random subset validates its parameters", {
  expect_error(createRandomSubset(numberOfSubjects = 0, randomSeed = 1))
  expect_error(createRandomSubset(numberOfSubjects = 10, randomSeed = 1.5))
  expect_error(createRandomSubset(numberOfSubjects = 10, randomSeed = NA_integer_))
})


test_that("Random subset stores deterministic settings in its list representation", {
  randomSubset <- createRandomSubset(
    numberOfSubjects = 10,
    randomSeed = 9876
  )

  operatorList <- randomSubset$toList()

  expect_equal(operatorList$numberOfSubjects, 10L)
  expect_equal(operatorList$randomSeed, 9876L)
})


test_that("Random subset query contains a deterministic seed-based ordering", {
  subsetDefinition <- CohortGenerator::createCohortSubsetDefinition(
    name = "random",
    definitionId = 301,
    subsetOperators = list(
      createRandomSubset(numberOfSubjects = 10, randomSeed = 12345)
    )
  )

  sql <- subsetDefinition$getSubsetQuery(c(2, 2002))
  sqliteSql <- SqlRender::translate(sql, targetDialect = "sqlite")

  expect_match(sql, "1103515245")
  expect_match(sql, "12345")
  expect_no_match(sqliteSql, "CHECKSUM")
  expect_match(sqliteSql, "1103515245")
})

test_that("Random subset query uses BigQuery-compatible modulo syntax", {
  subsetDefinition <- CohortGenerator::createCohortSubsetDefinition(
    name = "random",
    definitionId = 301,
    subsetOperators = list(
      createRandomSubset(numberOfSubjects = 10, randomSeed = 12345)
    )
  )

  bigquerySql <- subsetDefinition$getSubsetQuery(c(2, 2002)) |>
    SqlRender::translate(targetDialect = "bigquery")

  expect_match(bigquerySql, "mod\\(")
  expect_no_match(bigquerySql, "%")
})
